CREATE TABLE tasks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL CHECK (length(trim(title)) > 0),
    description TEXT,
    status TEXT NOT NULL DEFAULT 'assigned'
        CHECK (status IN ('assigned', 'in_progress', 'completed')),
    priority TEXT NOT NULL DEFAULT 'medium'
        CHECK (priority IN ('low', 'medium', 'high')),
    due_at TEXT,
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL,
    deleted_at TEXT
);
CREATE TABLE task_assignees (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    task_id BIGINT NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,
    assignee_name TEXT NOT NULL,
    PRIMARY KEY (task_id, assignee_name)
);
CREATE TABLE task_tags (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    task_id BIGINT NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,
    tag TEXT NOT NULL,
    PRIMARY KEY (task_id, tag)
);
CREATE TABLE task_labels (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    task_id BIGINT NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,
    label TEXT NOT NULL,
    PRIMARY KEY (task_id, label)
);
CREATE INDEX idx_team_todo_tasks_status_deleted_created
    ON tasks(status, deleted_at, created_at);
CREATE INDEX idx_team_todo_tasks_due_at ON tasks(due_at);
CREATE INDEX idx_team_todo_assignees_name_task
    ON task_assignees(assignee_name, task_id);
CREATE INDEX idx_team_todo_tags_tag_task ON task_tags(tag, task_id);
CREATE INDEX idx_team_todo_labels_label_task ON task_labels(label, task_id);
