-- Apply once as an administrator after checking the target database.
-- Creates only the ordinary Todo schema and a NOLOGIN runtime role.
-- Existing Kanban tables and ttodo_worker grants are not changed.
-- Credentials and LOGIN activation are managed separately.

BEGIN;
CREATE ROLE ttodo_todo_server
    NOLOGIN NOSUPERUSER NOINHERIT NOCREATEDB NOCREATEROLE
    NOREPLICATION NOBYPASSRLS;
CREATE SCHEMA todo_app AUTHORIZATION postgres;
REVOKE ALL ON SCHEMA todo_app FROM PUBLIC, anon, authenticated, service_role;
GRANT USAGE ON SCHEMA todo_app TO ttodo_todo_server;
GRANT CONNECT ON DATABASE postgres TO ttodo_todo_server;
ALTER ROLE ttodo_todo_server IN DATABASE postgres
    SET search_path = todo_app, pg_catalog;
SET LOCAL search_path = todo_app, pg_catalog;

CREATE TABLE tasks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL CHECK (length(trim(title)) > 0),
    description TEXT,
    status TEXT NOT NULL DEFAULT 'assigned'
        CHECK (status IN ('assigned', 'in_progress', 'completed')),
    priority TEXT NOT NULL DEFAULT 'medium'
        CHECK (priority IN ('low', 'medium', 'high')),
    due_at TEXT,
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL,
    deleted_at TEXT
);
CREATE TABLE task_assignees (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    task_id BIGINT NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,
    assignee_name TEXT NOT NULL,
    PRIMARY KEY (task_id, assignee_name)
);
CREATE TABLE task_tags (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    task_id BIGINT NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,
    tag TEXT NOT NULL,
    PRIMARY KEY (task_id, tag)
);
CREATE TABLE task_labels (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    task_id BIGINT NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,
    label TEXT NOT NULL,
    PRIMARY KEY (task_id, label)
);
CREATE INDEX idx_team_todo_tasks_status_deleted_created
    ON tasks(status, deleted_at, created_at);
CREATE INDEX idx_team_todo_tasks_due_at ON tasks(due_at);
CREATE INDEX idx_team_todo_assignees_name_task
    ON task_assignees(assignee_name, task_id);
CREATE INDEX idx_team_todo_tags_tag_task ON task_tags(tag, task_id);
CREATE INDEX idx_team_todo_labels_label_task ON task_labels(label, task_id);

REVOKE ALL ON TABLE
    todo_app.tasks, todo_app.task_assignees,
    todo_app.task_tags, todo_app.task_labels
FROM PUBLIC, anon, authenticated, service_role;
REVOKE ALL ON SEQUENCE
    todo_app.tasks_id_seq, todo_app.task_assignees_id_seq,
    todo_app.task_tags_id_seq, todo_app.task_labels_id_seq
FROM PUBLIC, anon, authenticated, service_role;

GRANT SELECT ON TABLE
    todo_app.tasks, todo_app.task_assignees,
    todo_app.task_tags, todo_app.task_labels
TO ttodo_todo_server;
GRANT INSERT (title, description, status, priority, due_at, created_at, updated_at)
    ON todo_app.tasks TO ttodo_todo_server;
GRANT UPDATE (title, description, status, priority, due_at, updated_at, deleted_at)
    ON todo_app.tasks TO ttodo_todo_server;
GRANT INSERT (task_id, assignee_name)
    ON todo_app.task_assignees TO ttodo_todo_server;
GRANT INSERT (task_id, tag) ON todo_app.task_tags TO ttodo_todo_server;
GRANT INSERT (task_id, label) ON todo_app.task_labels TO ttodo_todo_server;
GRANT DELETE ON TABLE
    todo_app.task_assignees, todo_app.task_tags, todo_app.task_labels
TO ttodo_todo_server;

ALTER TABLE todo_app.tasks ENABLE ROW LEVEL SECURITY;
ALTER TABLE todo_app.task_assignees ENABLE ROW LEVEL SECURITY;
ALTER TABLE todo_app.task_tags ENABLE ROW LEVEL SECURITY;
ALTER TABLE todo_app.task_labels ENABLE ROW LEVEL SECURITY;
CREATE POLICY todo_server_access ON todo_app.tasks
    TO ttodo_todo_server USING (true) WITH CHECK (true);
CREATE POLICY todo_server_access ON todo_app.task_assignees
    TO ttodo_todo_server USING (true) WITH CHECK (true);
CREATE POLICY todo_server_access ON todo_app.task_tags
    TO ttodo_todo_server USING (true) WITH CHECK (true);
CREATE POLICY todo_server_access ON todo_app.task_labels
    TO ttodo_todo_server USING (true) WITH CHECK (true);
COMMIT;
